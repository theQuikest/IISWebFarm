BeforeAll {
    . $PSScriptRoot\..\..\Classes\IISWebFarmExitCode.ps1

    . $PSScriptRoot\..\..\Classes\IISWebFarmException.ps1

    . $PSScriptRoot\..\..\Classes\SettingsValidationException.ps1

    . $PSScriptRoot\..\..\Private\Resolve-Checks.ps1
} #BeforeAll

Describe 'Resolve-Checks' {
    It 'Expands All into all supported checks' {
        $Result = Resolve-Checks `
            -Checks @('All')

        $Result |
            Should -Contain 'HealthProbe'

        $Result |
            Should -Contain 'DNS'

        $Result |
            Should -Contain 'HTTPS'

        $Result |
            Should -Contain 'Websites'

        $Result |
            Should -Contain 'ApplicationPools'

        $Result |
            Should -Contain 'WebDeploy'

        $Result.Count |
            Should -Be 6
    } #it

    It 'Returns individual checks unchanged' {
        $Result = Resolve-Checks `
            -Checks @(
                'HealthProbe',
                'DNS'
            )

        $Result.Count |
            Should -Be 2

        $Result |
            Should -Contain 'HealthProbe'

        $Result |
            Should -Contain 'DNS'
    } #it

    It 'Removes duplicate values' {
        $Result = Resolve-Checks `
            -Checks @(
                'HealthProbe',
                'HealthProbe',
                'DNS',
                'DNS'
            )

        $Result.Count |
            Should -Be 2
    } #it

    It 'Removes duplicate values generated by All' {
        $Result = Resolve-Checks `
            -Checks @(
                'All',
                'HealthProbe'
            )

        $Result.Count |
            Should -Be 6
    } #it

    It 'Returns checks sorted consistently' {
        $Result = Resolve-Checks `
            -Checks @(
                'HTTPS',
                'DNS',
                'HealthProbe'
            )

        $Result |
            Should -Be @(
                'DNS',
                'HTTPS',
                'HealthProbe'
            )
    } #it

    It 'Throws SettingsValidationException when Checks is null' {
        {
            Resolve-Checks `
                -Checks $null

        } | Should -Throw `
            -ExceptionType SettingsValidationException
    } #it

    It 'Throws SettingsValidationException when Checks is empty' {
        {
            Resolve-Checks `
                -Checks @()

        } | Should -Throw `
            -ExceptionType SettingsValidationException
    } #it

    It 'Throws SettingsValidationException when unsupported checks are specified' {
        {
            Resolve-Checks `
                -Checks @(
                    'HealthProbe',
                    'Banana'
                )
        } | Should -Throw `
            -ExceptionType SettingsValidationException
    } #it
} #Describe Resolve-Checks